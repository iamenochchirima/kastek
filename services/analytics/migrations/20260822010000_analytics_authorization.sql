CREATE TABLE IF NOT EXISTS analytics.reporting_grant (
    grant_id TEXT PRIMARY KEY CHECK (length(trim(grant_id)) BETWEEN 1 AND 256),
    issuer_service_identity_id TEXT NOT NULL REFERENCES analytics.service_identity(service_identity_id),
    audience TEXT NOT NULL CHECK (length(trim(audience)) BETWEEN 1 AND 512),
    principal_type TEXT NOT NULL CHECK (
        principal_type IN ('user', 'service_identity', 'agent_installation')
    ),
    principal_id TEXT NOT NULL CHECK (length(trim(principal_id)) BETWEEN 1 AND 512),
    scope_id BIGINT NOT NULL REFERENCES analytics.reporting_scope(scope_id),
    root_scope_id BIGINT NOT NULL REFERENCES analytics.reporting_scope(scope_id),
    descendant_mode TEXT NOT NULL CHECK (descendant_mode IN ('none', 'all', 'explicit')),
    explicit_descendant_scope_ids JSONB NOT NULL DEFAULT '[]'::JSONB,
    permissions JSONB NOT NULL DEFAULT '[]'::JSONB,
    metric_keys JSONB NOT NULL DEFAULT '[]'::JSONB,
    dimension_keys JSONB NOT NULL DEFAULT '[]'::JSONB,
    policy_version TEXT NOT NULL CHECK (length(trim(policy_version)) BETWEEN 1 AND 128),
    issued_at TIMESTAMPTZ NOT NULL,
    not_before TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    correlation_id TEXT,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (expires_at > not_before),
    CHECK (expires_at <= issued_at + INTERVAL '120 seconds'),
    CHECK (
        (descendant_mode = 'explicit' AND jsonb_array_length(explicit_descendant_scope_ids) > 0)
        OR (descendant_mode IN ('none', 'all') AND jsonb_array_length(explicit_descendant_scope_ids) = 0)
    )
);

CREATE INDEX IF NOT EXISTS reporting_grant_principal_idx
    ON analytics.reporting_grant (principal_type, principal_id, expires_at);

CREATE INDEX IF NOT EXISTS reporting_grant_scope_idx
    ON analytics.reporting_grant (scope_id, root_scope_id, expires_at);

CREATE OR REPLACE FUNCTION analytics.scope_is_authorized(candidate_scope_id BIGINT)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
AS $$
    SELECT candidate_scope_id = ANY(
        COALESCE(
            NULLIF(current_setting('analytics.authorized_scope_ids', TRUE), '')::BIGINT[],
            '{}'::BIGINT[]
        )
    );
$$;

CREATE OR REPLACE FUNCTION analytics.set_authorization_context(
    authorized_scope_ids BIGINT[],
    authorization_grant_id TEXT
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM set_config(
        'analytics.authorized_scope_ids',
        COALESCE(authorized_scope_ids::TEXT, '{}'),
        TRUE
    );
    PERFORM set_config(
        'analytics.authorization_grant_id',
        COALESCE(authorization_grant_id, ''),
        TRUE
    );
END;
$$;

CREATE OR REPLACE FUNCTION analytics.clear_authorization_context()
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM set_config('analytics.authorized_scope_ids', '{}', TRUE);
    PERFORM set_config('analytics.authorization_grant_id', '', TRUE);
END;
$$;

