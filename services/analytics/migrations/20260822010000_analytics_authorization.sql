CREATE TABLE IF NOT EXISTS analytics.scope_assignment (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_id BIGINT NOT NULL REFERENCES analytics.reporting_scope(scope_id) ON DELETE CASCADE,
    source_service TEXT NOT NULL CHECK (
        source_service IN ('core', 'agent-platform', 'tenant-platform')
    ),
    source_assignment_id TEXT NOT NULL CHECK (length(trim(source_assignment_id)) BETWEEN 1 AND 512),
    principal_type TEXT NOT NULL CHECK (
        principal_type IN ('user', 'service_identity', 'agent_installation')
    ),
    principal_id TEXT NOT NULL CHECK (length(trim(principal_id)) BETWEEN 1 AND 512),
    permission TEXT NOT NULL CHECK (length(trim(permission)) BETWEEN 1 AND 256),
    status TEXT NOT NULL CHECK (status IN ('active', 'revoked', 'expired')),
    starts_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ,
