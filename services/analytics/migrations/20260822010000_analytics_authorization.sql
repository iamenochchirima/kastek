-- A-05: reporting scopes, hierarchy, producer identities, assignments, grants, and RLS context.
-- Source services remain authoritative for users, roles, and assignments. These tables are the
-- Analytics-side registry and authorization read model; ingestion and reporting use them later.

CREATE TABLE IF NOT EXISTS analytics.scope_kind_registry (
    scope_kind TEXT PRIMARY KEY,
    major_version INTEGER NOT NULL CHECK (major_version > 0),
    owner_source_service TEXT NOT NULL CHECK (
        owner_source_service IN ('core', 'agent-platform', 'tenant-platform')
    ),
    parent_scope_kind TEXT REFERENCES analytics.scope_kind_registry(scope_kind),
    allows_children BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO analytics.scope_kind_registry (
    scope_kind,
    major_version,
    owner_source_service,
    parent_scope_kind,
    allows_children
)
VALUES
    ('core_organization', 1, 'core', NULL, FALSE),
    ('tenant_workspace', 1, 'tenant-platform', NULL, TRUE),
    ('tenant_client', 1, 'tenant-platform', 'tenant_workspace', FALSE)
ON CONFLICT (scope_kind) DO UPDATE
SET major_version = EXCLUDED.major_version,
    owner_source_service = EXCLUDED.owner_source_service,
    parent_scope_kind = EXCLUDED.parent_scope_kind,
    allows_children = EXCLUDED.allows_children,
    updated_at = NOW();

CREATE TABLE IF NOT EXISTS analytics.reporting_scope (
    scope_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_kind TEXT NOT NULL REFERENCES analytics.scope_kind_registry(scope_kind),
    owning_source_service TEXT NOT NULL CHECK (
        owning_source_service IN ('core', 'agent-platform', 'tenant-platform')
    ),
    external_source_id TEXT NOT NULL CHECK (length(trim(external_source_id)) BETWEEN 1 AND 512),
    root_scope_id BIGINT,
    parent_scope_id BIGINT,
    status TEXT NOT NULL CHECK (status IN ('active', 'suspended', 'deleted')),
    reporting_timezone TEXT NOT NULL CHECK (length(trim(reporting_timezone)) BETWEEN 1 AND 128),
    source_version BIGINT NOT NULL DEFAULT 1 CHECK (source_version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT reporting_scope_root_fk
        FOREIGN KEY (root_scope_id) REFERENCES analytics.reporting_scope(scope_id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT reporting_scope_parent_fk
        FOREIGN KEY (parent_scope_id) REFERENCES analytics.reporting_scope(scope_id),
    CONSTRAINT reporting_scope_not_own_parent CHECK (parent_scope_id IS NULL OR parent_scope_id <> scope_id),
    CONSTRAINT reporting_scope_external_identity UNIQUE (
        owning_source_service,
        scope_kind,
        external_source_id
    )
);

CREATE INDEX IF NOT EXISTS reporting_scope_root_status_idx
    ON analytics.reporting_scope (root_scope_id, status, scope_kind);

CREATE INDEX IF NOT EXISTS reporting_scope_parent_status_idx
    ON analytics.reporting_scope (parent_scope_id, status);

CREATE TABLE IF NOT EXISTS analytics.scope_ancestor (
    ancestor_scope_id BIGINT NOT NULL REFERENCES analytics.reporting_scope(scope_id) ON DELETE CASCADE,
    descendant_scope_id BIGINT NOT NULL REFERENCES analytics.reporting_scope(scope_id) ON DELETE CASCADE,
    depth INTEGER NOT NULL CHECK (depth >= 0),
    PRIMARY KEY (ancestor_scope_id, descendant_scope_id),
    CONSTRAINT scope_ancestor_depth_identity CHECK (
        (depth = 0 AND ancestor_scope_id = descendant_scope_id)
        OR (depth > 0 AND ancestor_scope_id <> descendant_scope_id)
    )
);

CREATE INDEX IF NOT EXISTS scope_ancestor_descendant_idx
    ON analytics.scope_ancestor (descendant_scope_id, ancestor_scope_id);

CREATE OR REPLACE FUNCTION analytics.validate_reporting_scope()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    parent_root BIGINT;
    parent_kind TEXT;
    expected_parent_kind TEXT;
BEGIN
    IF NEW.parent_scope_id IS NULL THEN
        IF NEW.root_scope_id IS NULL THEN
            NEW.root_scope_id := NEW.scope_id;
        END IF;
        IF NEW.root_scope_id <> NEW.scope_id THEN
            RAISE EXCEPTION 'Root scope must point to itself for a root reporting scope';
        END IF;
    ELSE
        IF TG_OP = 'UPDATE' AND NEW.parent_scope_id IS DISTINCT FROM OLD.parent_scope_id THEN
            RAISE EXCEPTION 'Reporting scope reparenting requires a controlled migration';
        END IF;

        SELECT scope_kind, root_scope_id
        INTO parent_kind, parent_root
        FROM analytics.reporting_scope
        WHERE scope_id = NEW.parent_scope_id
          AND status <> 'deleted';

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Reporting scope parent % does not exist or is deleted', NEW.parent_scope_id;
        END IF;

        SELECT parent_scope_kind
        INTO expected_parent_kind
        FROM analytics.scope_kind_registry
        WHERE scope_kind = NEW.scope_kind
          AND active;

        IF expected_parent_kind IS NULL OR expected_parent_kind <> parent_kind THEN
            RAISE EXCEPTION 'Scope kind % cannot be attached to parent kind %', NEW.scope_kind, parent_kind;
        END IF;

        IF NEW.root_scope_id IS NULL THEN
            NEW.root_scope_id := parent_root;
        ELSIF NEW.root_scope_id <> parent_root THEN
            RAISE EXCEPTION 'Reporting scope root does not match its parent root';
        END IF;
    END IF;

    IF TG_OP = 'UPDATE' AND (
        NEW.scope_kind IS DISTINCT FROM OLD.scope_kind
        OR NEW.owning_source_service IS DISTINCT FROM OLD.owning_source_service
        OR NEW.external_source_id IS DISTINCT FROM OLD.external_source_id
        OR NEW.root_scope_id IS DISTINCT FROM OLD.root_scope_id
    ) THEN
        RAISE EXCEPTION 'Reporting scope identity and hierarchy are immutable';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS reporting_scope_validate_trigger ON analytics.reporting_scope;
CREATE TRIGGER reporting_scope_validate_trigger
BEFORE INSERT OR UPDATE ON analytics.reporting_scope
FOR EACH ROW EXECUTE FUNCTION analytics.validate_reporting_scope();

CREATE OR REPLACE FUNCTION analytics.insert_scope_ancestor_rows()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO analytics.scope_ancestor (ancestor_scope_id, descendant_scope_id, depth)
    VALUES (NEW.scope_id, NEW.scope_id, 0);

    IF NEW.parent_scope_id IS NOT NULL THEN
        INSERT INTO analytics.scope_ancestor (ancestor_scope_id, descendant_scope_id, depth)
        SELECT ancestor_scope_id, NEW.scope_id, depth + 1
        FROM analytics.scope_ancestor
        WHERE descendant_scope_id = NEW.parent_scope_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS reporting_scope_ancestor_trigger ON analytics.reporting_scope;
CREATE TRIGGER reporting_scope_ancestor_trigger
AFTER INSERT ON analytics.reporting_scope
FOR EACH ROW EXECUTE FUNCTION analytics.insert_scope_ancestor_rows();

