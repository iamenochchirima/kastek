import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import type { Pool } from 'pg';
import { buildApp } from '../src/app.js';
import { readConfig } from '../src/config.js';
import { CORE_REGISTRARS } from '../src/main.js';
import { RUST_JSON_NUMERIC_FIELDS, RUST_JSON_VALUE_FIELDS, RUST_JSON_VALUE_ROUTES } from '../src/identity/json-number-contracts.js';
import { PRODUCT_AGENT_BODY_SHAPES } from '../src/identity/product-agent-body-shapes.js';
import { GENERATED_SERDE_BODY_SCHEMAS } from '../src/identity/json-body-schemas.generated.js';

// Preserve source-owned DTO number/shape rules only while their route remains registered.
const apiRoot=new URL('../',import.meta.url), routes=new Set<string>(['GET /','GET /health']), currentSchemas:Record<string,unknown>={};
const app=await buildApp({config:readConfig({DATABASE_URL:'postgres://unused',LOG_LEVEL:'silent'}),pool:{query(){throw Error('Contract generation must not access a database');}} as unknown as Pool},[
  instance=>{instance.addHook('onRoute',route=>{
    for(const method of Array.isArray(route.method)?route.method:[route.method]){
      if(method==='HEAD')continue;
      const key=method+' '+route.url;routes.add(key);
      if(route.schema?.body)currentSchemas[key]=route.schema.body;
    }
  });},...CORE_REGISTRARS,
]);
try{
  await app.ready();
  const pick=(value:Record<string,unknown>)=>Object.fromEntries(Object.entries(value).filter(([key])=>routes.has(key)).sort(([a],[b])=>a.localeCompare(b)));
  const numeric=pick(RUST_JSON_NUMERIC_FIELDS),values=[...RUST_JSON_VALUE_ROUTES].filter(key=>routes.has(key)).sort(),fields=pick(RUST_JSON_VALUE_FIELDS);
  const shapes=pick({...GENERATED_SERDE_BODY_SCHEMAS,...currentSchemas,...PRODUCT_AGENT_BODY_SHAPES});
  const header='// Generated by scripts/refresh-route-contracts.ts from current registered routes and their retained DTO contracts.\n';
  const numbers=header+'export const RUST_JSON_NUMERIC_FIELDS: Record<string, readonly (readonly [readonly string[], string])[]> = '+JSON.stringify(numeric,null,2)+';\n\n'+
    'export const RUST_JSON_VALUE_ROUTES = new Set('+JSON.stringify(values,null,2)+');\n\n'+
    'export const RUST_JSON_VALUE_FIELDS: Record<string, readonly (readonly string[])[]> = '+JSON.stringify(fields,null,2)+';\n';
  const bodies=header+'export const GENERATED_SERDE_BODY_SCHEMAS: Record<string, unknown> = '+JSON.stringify(shapes,null,2)+' as const;\n';
  const census=JSON.stringify({version:1,generatedBy:'scripts/refresh-route-contracts.ts',routeCount:routes.size,routes:[...routes].sort()},null,2)+'\n';
  const outputs:[URL,string][]=[[new URL('src/identity/json-number-contracts.ts',apiRoot),numbers],[new URL('src/identity/json-body-schemas.generated.ts',apiRoot),bodies],[new URL('tests/fixtures/routes.json',apiRoot),census]];
  if(process.argv.includes('--write')){
    for(const [path,content] of outputs)await writeFile(path,content);
    process.stdout.write('Updated current route and JSON contracts for '+routes.size+' routes.\n');
  }else{
    for(const [path,content] of outputs)if(await readFile(path,'utf8')!==content)throw Error('Stale route contract: '+fileURLToPath(path));
    process.stdout.write('Current route and JSON contracts match '+routes.size+' routes.\n');
  }
}finally{await app.close();}
