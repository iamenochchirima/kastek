import { readFile, writeFile, readdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { build } from "esbuild";
const base = new URL("../", import.meta.url);
const [template, css, bundle] = await Promise.all([
  readFile(new URL("mcp-app/content-review.html", base), "utf8"),
  readFile(new URL("mcp-app/content-review.css", base), "utf8"),
  build({ absWorkingDir: base.pathname, entryPoints: ["mcp-app/content-review.ts"], bundle: true, write: false, format: "esm", platform: "browser", target: "es2022", minify: true, drop: ["console"], legalComments: "inline", metafile: true }),
]);
// Retain notices only for package inputs that contribute bytes to the emitted browser bundle.
const packageRoots = new Map();
const bundledInputs = new Set(Object.values(bundle.metafile.outputs).flatMap(output => Object.entries(output.inputs).filter(([, value]) => value.bytesInOutput > 0).map(([input]) => input)));
for (const input of bundledInputs) {
  if (!input.includes("node_modules/")) continue;
  let directory = dirname(resolve(fileURLToPath(base), input));
  while (directory !== dirname(directory)) {
    let metadata;
    try { metadata = JSON.parse(await readFile(join(directory, "package.json"), "utf8")); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    if (metadata?.name && metadata.version) { packageRoots.set(directory, metadata); break; }
    directory = dirname(directory);
  }
}
const notices = [];
for (const [directory, metadata] of [...packageRoots].sort(([, first], [, second]) => `${first.name}@${first.version}`.localeCompare(`${second.name}@${second.version}`))) {
  const files = (await readdir(directory)).filter(name => /^(?:licen[cs]e|copying|notice)(?:[._-].*)?$/i.test(name)).sort();
  if (!files.length) throw new Error(`Missing bundled dependency license: ${metadata.name}`);
  const content = await Promise.all(files.map(async name => `${name}\n${await readFile(join(directory, name), "utf8")}`));
  notices.push(`${metadata.name}@${metadata.version} (${metadata.license ?? "see license"})\n${content.join("\n")}`);
}
const escapeHtml = value => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
const noticeTemplate = `<template id="growth-content-third-party-notices">${escapeHtml(notices.join("\n\n"))}</template>`;
const script = bundle.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const integrity = value => createHash("sha256").update(value).digest("base64");
const csp = `default-src 'none'; script-src 'sha256-${integrity(script)}'; style-src 'sha256-${integrity(css)}'; img-src __GROWTH_MEDIA_ORIGIN__; media-src __GROWTH_MEDIA_ORIGIN__; base-uri 'none'; form-action 'none'`;
const html = template.replace("<!-- CONTENT_REVIEW_CSP -->", `<meta http-equiv="Content-Security-Policy" content="${csp}">`).replace("/* CONTENT_REVIEW_CSS */", () => css).replace("/* CONTENT_REVIEW_JS */", () => script).replace("</body>", () => `${noticeTemplate}</body>`);
await writeFile(new URL("src/operations/content-mcp-app-ui.generated.ts", base), `// Generated by scripts/build-content-mcp-app.mjs; do not edit.\nexport const contentMcpAppHtml: string = ${JSON.stringify(html)};\n`);
console.log("Built Growth content review UI");
