//! Route registration for the `internal` boundary.

use actix_web::web;

#[allow(unused_imports)]
use crate::controllers::{
    admin, admin_billing, admin_conversations, admin_invoices, admin_leads, admin_notifications,
    admin_outreach, admin_quotations, admin_web_services, agent_internal, agent_platform, ai, auth,
    billing, bookings, calls, connections, customers, health, inbox, notifications, onboarding,
    orgs, product_tour, profile, public_v1, realtime, social, whatsapp, whatsapp_calls, workspace,
};

pub fn configure(cfg: &mut web::ServiceConfig) {
    cfg.service(
        web::scope("/api/realtime").route("/whatsapp", web::get().to(realtime::whatsapp_stream)),
    );
    cfg.service(
        web::scope("/api/internal/agents/v1")
            .route(
                "/customers/{id}",
                web::get().to(agent_internal::get_customer),
            )
            .route(
                "/workspace/status",
                web::get().to(agent_internal::get_workspace_status),
            )
            .route(
                "/bookings/services",
                web::get().to(agent_internal::list_booking_services),
            )
            .route(
                "/content/posts",
                web::get().to(agent_internal::list_content_posts),
            )
            .route(
                "/content/posts",
                web::post().to(agent_internal::create_content_draft),
            )
            .route(
                "/content/posts/{id}",
                web::get().to(agent_internal::get_content_post),
            )
            .route(
                "/content/posts/{id}",
                web::patch().to(agent_internal::update_content_draft),
            )
            .route(
                "/content/posts/{id}/publish",
                web::post().to(agent_internal::publish_content_post),
            )
            .route(
                "/content/posts/{id}/schedule",
                web::post().to(agent_internal::schedule_content_post),
            )
            .route(
                "/content/posts/{id}/unschedule",
                web::post().to(agent_internal::unschedule_content_post),
            )
            .route(
                "/content/posts/{id}",
                web::delete().to(agent_internal::delete_content_post),
            )
            .route(
                "/channels/deliver",
                web::post().to(agent_internal::deliver_channel_message),
            ),
    );
    cfg.service(
        web::scope("/api/agents")
            .route("", web::get().to(agent_platform::list_agents))
            .route("", web::post().to(agent_platform::create_agent))
            .route(
                "/operations/summary",
                web::get().to(agent_platform::operations_summary),
            )
            .route(
                "/operations/runs",
                web::get().to(agent_platform::operations_runs),
            )
            .route(
                "/operations/health",
                web::get().to(agent_platform::operations_health),
            )
            .route(
                "/operations/effects/reconciliation",
                web::get().to(agent_platform::operations_effects_reconciliation),
            )
            .route(
                "/operations/effects/{effectId}/reconcile",
                web::post().to(agent_platform::reconcile_effect),
            )
            .route(
                "/operations/kill-switches",
                web::get().to(agent_platform::list_kill_switches),
            )
            .route(
                "/operations/kill-switches",
                web::post().to(agent_platform::create_kill_switch),
            )
            .route(
                "/operations/kill-switches/{switchId}",
                web::delete().to(agent_platform::disable_kill_switch),
            )
            .route("/audit", web::get().to(agent_platform::list_audit))
            .route("/templates", web::get().to(agent_platform::list_templates))
            .route(
                "/templates/{templateKey}/install",
                web::post().to(agent_platform::install_template),
            )
            .route(
                "/installations/{installationId}/status/{status}",
                web::post().to(agent_platform::set_installation_status),
            )
            .route(
                "/installations",
                web::post().to(agent_platform::create_installation),
            )
            .route(
                "/installations/{installationId}/settings",
                web::patch().to(agent_platform::set_installation_settings),
            )
            .route(
                "/installations/{installationId}/credentials",
                web::get().to(agent_platform::list_installation_credentials),
            )
            .route(
                "/installations/{installationId}/credentials",
                web::post().to(agent_platform::create_installation_credential),
            )
            .route(
                "/installations/{installationId}/credentials/{credentialId}",
                web::delete().to(agent_platform::revoke_installation_credential),
            )
            .route(
                "/installations/{installationId}/credentials/{credentialId}/rotate",
                web::post().to(agent_platform::rotate_installation_credential),
            )
            .route(
                "/installations/{installationId}/capabilities",
                web::get().to(agent_platform::list_installation_capabilities),
            )
            .route(
                "/installations/{installationId}/grants",
                web::get().to(agent_platform::list_installation_grants),
            )
            .route(
                "/installations/{installationId}/grants/resources",
                web::post().to(agent_platform::grant_installation_resource),
            )
            .route(
                "/installations/{installationId}/grants/connectors",
                web::post().to(agent_platform::grant_installation_connector),
            )
            .route(
                "/installations/{installationId}/tools",
                web::post().to(agent_platform::grant_installation_tool),
            )
            .route(
                "/connectors",
                web::get().to(agent_platform::list_connectors),
            )
            .route(
                "/installations/{installationId}/connectors",
                web::get().to(agent_platform::list_installation_connectors),
            )
            .route(
                "/installations/{installationId}/runs",
                web::get().to(agent_platform::list_installation_runs),
            )
            .route(
                "/installations/{installationId}/schedules",
                web::get().to(agent_platform::list_installation_schedules),
            )
            .route(
                "/installations/{installationId}/schedules",
                web::post().to(agent_platform::create_installation_schedule),
            )
            .route(
                "/schedules/{scheduleId}/status/{status}",
                web::post().to(agent_platform::set_schedule_status),
            )
            .route(
                "/knowledge/sources",
                web::get().to(agent_platform::list_knowledge_sources),
            )
            .route(
                "/knowledge/sources",
                web::post().to(agent_platform::create_knowledge_source),
            )
            .route(
                "/knowledge/sources/{sourceId}/ingest-url",
                web::post().to(agent_platform::ingest_knowledge_source_url),
            )
            .route(
                "/knowledge/sources/{sourceId}",
                web::delete().to(agent_platform::delete_knowledge_source),
            )
            .route("/memory", web::get().to(agent_platform::list_memory))
            .route(
                "/memory/{memoryId}",
                web::delete().to(agent_platform::delete_memory),
            )
            .route(
                "/memory/{memoryId}/revalidate",
                web::post().to(agent_platform::revalidate_memory),
            )
            .route(
                "/{agentId}/versions",
                web::get().to(agent_platform::list_agent_versions),
            )
            .route(
                "/{agentId}/versions",
                web::post().to(agent_platform::create_agent_version),
            )
            .route(
                "/{agentId}/versions/{versionId}/publish",
                web::post().to(agent_platform::publish_agent_version),
            )
            .route(
                "/{agentId}/versions/{versionId}/rollback",
                web::post().to(agent_platform::rollback_agent_version),
            )
            .route(
                "/{agentId}/versions/{versionId}/retire",
                web::post().to(agent_platform::retire_agent_version),
            )
            .route(
                "/{agentId}/archive",
                web::post().to(agent_platform::archive_agent),
            )
            .route(
                "/kasiai/ensure",
                web::post().to(agent_platform::ensure_kasiai),
            )
            .route(
                "/installations/{installationId}/platform/conversation",
                web::post().to(agent_platform::resolve_conversation),
            )
            .route(
                "/installations/{installationId}/platform/conversation/new",
                web::post().to(agent_platform::create_conversation),
            )
            .route(
                "/installations/{installationId}/conversations",
                web::get().to(agent_platform::list_conversations),
            )
            .route(
                "/installations/{installationId}/kasiai/home",
                web::post().to(agent_platform::kasiai_home),
            )
            .route(
                "/installations/{installationId}/kasiai/preferences",
                web::get().to(agent_platform::kasiai_preferences),
            )
            .route(
                "/installations/{installationId}/kasiai/preferences",
                web::patch().to(agent_platform::update_kasiai_preferences),
            )
            .route(
                "/conversations/{conversationId}",
                web::patch().to(agent_platform::update_conversation),
            )
            .route(
                "/conversations/{conversationId}/channel-default",
                web::post().to(agent_platform::set_channel_default_conversation),
            )
            .route(
                "/conversations/{conversationId}/status/{status}",
                web::post().to(agent_platform::set_conversation_status),
            )
            .route(
                "/conversations/{conversationId}/restore",
                web::post().to(agent_platform::restore_conversation),
            )
            .route(
                "/installations/{installationId}/channels",
                web::get().to(agent_platform::list_channels),
            )
            .route(
                "/installations/{installationId}/channels",
                web::post().to(agent_platform::create_channel_connection),
            )
            .route(
                "/installations/{installationId}/channels/{connectionId}/pairing",
                web::post().to(agent_platform::issue_channel_pairing),
            )
            .route(
                "/kasiai/channels/whatsapp/pairing",
                web::post().to(agent_platform::issue_kasiai_whatsapp_pairing),
            )
            .route(
                "/channel-bindings/{bindingId}",
                web::delete().to(agent_platform::disconnect_channel),
            )
            .route(
                "/installations/{installationId}/platform/messages",
                web::post().to(agent_platform::send_message),
            )
            .route(
                "/conversations/{conversationId}",
                web::get().to(agent_platform::get_conversation),
            )
            .route("/runs/{runId}", web::get().to(agent_platform::get_run))
            .route(
                "/runs/{runId}/timeline",
                web::get().to(agent_platform::get_run_timeline),
            )
            .route(
                "/runs/{runId}/cancel",
                web::post().to(agent_platform::cancel_run),
            )
            .route(
                "/runs/{runId}/external-event",
                web::post().to(agent_platform::signal_external_event),
            )
            .route(
                "/runs/{runId}/approval",
                web::post().to(agent_platform::approve_run),
            )
            .route(
                "/runs/{runId}/events/stream",
                web::get().to(agent_platform::stream_run),
            ),
    );
}
