export function rowView(
  name: string,
  row: Record<string, unknown>,
): Record<string, unknown> {
  const mapping = ROW_FIELDS[name];
  if (!mapping) throw new Error(`Unknown admin row ${name}`);
  return Object.fromEntries(
    Object.entries(mapping).map(([wire, sql]) => [
      wire,
      wire === 'quote_amount' && typeof row[sql] === 'number'
        ? serdeFloat(row[sql] as number)
        : (row[sql] ?? null),
    ]),
  );
}
