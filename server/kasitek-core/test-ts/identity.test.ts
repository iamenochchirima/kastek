import test from 'node:test';
import assert from 'node:assert/strict';
import { generateKeyPair, SignJWT } from 'jose';
import { safeReturnPath, authenticationDeadline } from '../src-ts/routes/auth.js';
import { validateLogoutEvent, verifyLogoutToken } from '../src-ts/identity/logout.js';
import { interactiveActivity, requireOrigin } from '../src-ts/identity/session.js';
import type { CoreContext } from '../src-ts/context.js';
import type { FastifyRequest } from 'fastify';
test('return paths stay on the product origin and original authentication cannot extend', () => {
  for (const value of ['//evil.test','https://evil.test','/\\evil.test','/\nfoo']) assert.equal(safeReturnPath(value), false);
  assert.equal(safeReturnPath('/invitations/abc?tab=team'), true);
  const now = 1700000000000;
  assert.throws(() => authenticationDeadline(undefined, now));
  assert.throws(() => authenticationDeadline((now - 30*86400000)/1000, now));
  assert.throws(() => authenticationDeadline((now+60000)/1000, now));
  const authTime = (now - 20*86400000)/1000;
  assert.equal(authenticationDeadline(authTime, now).valueOf(), authTime*1000+30*86400000);
});
test('background traffic never refreshes identity idle and unsafe cookie requests require exact Origin', () => {
  const base = { method: 'GET', url: '/api/inbox', headers: {} };
  assert.equal(interactiveActivity(base), false);
  assert.equal(interactiveActivity({ ...base, method: 'POST', headers: { 'x-kasitek-background': '1' } }), false);
  assert.equal(interactiveActivity({ ...base, method: 'POST', url: '/api/notifications/read' }), false);
  assert.equal(interactiveActivity({ ...base, method: 'POST', url: '/api/auth/activity' }), true);
  const context = { config: { frontendUrl: 'https://growth.test/path' } } as CoreContext;
  for (const origin of [undefined, 'null','https://evil.test','https://growth.test.evil','http://growth.test']) assert.throws(() => requireOrigin({ headers: { origin } } as FastifyRequest, context));
  requireOrigin({ headers: { origin: 'https://growth.test' } } as FastifyRequest, context);
});
test('logout verifies real signatures, audience, issuer, freshness and event shape', async () => {
  const keys = await generateKeyPair('RS256');
  const wrong = await generateKeyPair('RS256');
  const now = Math.floor(Date.now()/1000);
  const payload = { iss: 'https://issuer.test', aud: 'growth', iat: now, jti: 'one', sid: 'browser', events: { 'http://schemas.openid.net/event/backchannel-logout': {} } };
  const token = await new SignJWT(payload).setProtectedHeader({ alg: 'RS256' }).sign(keys.privateKey);
  await verifyLogoutToken(token, keys.publicKey, payload.iss, 'growth');
  await assert.rejects(verifyLogoutToken(token, wrong.publicKey, payload.iss, 'growth'));
  await assert.rejects(verifyLogoutToken(token, keys.publicKey, 'https://other.test', 'growth'));
  await assert.rejects(verifyLogoutToken(token, keys.publicKey, payload.iss, 'other'));
  assert.throws(() => validateLogoutEvent({ ...payload, nonce: 'login' }, payload.iss, now));
  assert.throws(() => validateLogoutEvent({ ...payload, events: {} }, payload.iss, now));
  assert.throws(() => validateLogoutEvent({ ...payload, iat: now-301 }, payload.iss, now));
  assert.throws(() => validateLogoutEvent({ ...payload, sid: undefined }, payload.iss, now));
});
