import type { CapabilityManifest, CapabilityManifestMetadata, ToolRiskClass } from "../tools/types";

export interface GeneratedCapabilitySurface {
  name: string;
  version: string;
  description: string;
  riskClass: ToolRiskClass;
  requiresApproval: boolean;
  timeoutMs: number;
  inputSchema: Record<string, unknown>;
  outputSchema: Record<string, unknown>;
  manifest: CapabilityManifestMetadata;
  mcp: {
    name: string;
    description: string;
    inputSchema: Record<string, unknown>;
  };
  permission: {
    scope: string;
    label: string;
    resourceType?: string;
  };
  audit: {
    classification: CapabilityManifestMetadata["auditClassification"];
    description: string;
    redaction: string[];
  };
  documentation: {
    title: string;
    summary: string;
  };
}

function titleCase(value: string): string {
  return value
    .replace(/[._:-]+/g, " ")
    .replace(/\b\w/g, (character) => character.toUpperCase());
}

function surfaceFor(manifest: CapabilityManifest): GeneratedCapabilitySurface {
  const metadata = manifest.manifest;
  const resourceType = metadata.resourceSelector?.type;
  const permissionLabel = `${titleCase(metadata.requiredScope)} permission`;
  const auditDescription = `${manifest.description} This ${manifest.riskClass} capability is owned by ${metadata.ownerService} and requires ${metadata.requiredScope}.`;
  return {
    name: manifest.name,
    version: manifest.version,
    description: manifest.description,
    riskClass: manifest.riskClass,
    requiresApproval: manifest.requiresApproval,
    timeoutMs: manifest.timeoutMs,
    inputSchema: manifest.inputSchema,
    outputSchema: manifest.outputSchema,
    manifest: {
      ...metadata,
      redaction: [...metadata.redaction],
      ...(metadata.resourceSelector ? { resourceSelector: { ...metadata.resourceSelector } } : {}),
    },
    mcp: {
      name: manifest.name,
      description: manifest.description,
      inputSchema: manifest.inputSchema,
    },
    permission: {
      scope: metadata.requiredScope,
      label: permissionLabel,
      ...(resourceType ? { resourceType } : {}),
    },
    audit: {
      classification: metadata.auditClassification,
      description: auditDescription,
      redaction: [...metadata.redaction],
    },
    documentation: {
      title: titleCase(manifest.name),
      summary: manifest.description,
    },
  };
}

/** Projects the authoritative registry into every non-handler consumer surface. */
export function generateCapabilitySurfaces(manifests: readonly CapabilityManifest[]): GeneratedCapabilitySurface[] {
  return manifests.map(surfaceFor);
}

export function generateCapabilityDocumentation(manifests: readonly CapabilityManifest[]): string {
  const surfaces = generateCapabilitySurfaces(manifests);
  const sections = surfaces.map((surface) => [
    `## ${surface.name} (${surface.version})`,
    "",
    surface.documentation.summary,
    "",
    `- Owner: \`${surface.manifest.ownerService}\``,
    `- Permission: \`${surface.permission.scope}\` (${surface.permission.label})`,
    `- Risk: \`${surface.riskClass}\`; execution: \`${surface.manifest.execution}\`; approval: \`${surface.manifest.approval}\``,
    `- Idempotency: \`${surface.manifest.idempotency}\`; timeout: ${surface.timeoutMs}ms`,
    ...(surface.permission.resourceType ? [`- Resource scope: \`${surface.permission.resourceType}\``] : []),
    `- Audit: \`${surface.audit.classification}\`; redacts: ${surface.audit.redaction.length ? surface.audit.redaction.map((entry) => `\`${entry}\``).join(", ") : "none"}`,
    "",
    "### Input schema",
    "",
    "```json",
    JSON.stringify(surface.inputSchema, null, 2),
    "```",
    "",
    "### Output schema",
    "",
    "```json",
    JSON.stringify(surface.outputSchema, null, 2),
    "```",
  ].join("\n"));
  return [
    "# Generated agent capability catalog",
    "",
    "This file is generated from the versioned `CapabilityManifest` registry. Update the manifest and run `pnpm generate:capabilities`; do not edit this file directly.",
    "",
    ...sections,
    "",
  ].join("\n");
}
